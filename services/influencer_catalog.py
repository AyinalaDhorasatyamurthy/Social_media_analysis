def _matches_region(inf: Dict[str, Any], target_code: str, raw_query: str) -> bool:
    inf_country = (inf.get("country") or "").upper()
    inf_region = (inf.get("region") or "").lower()
    inf_state = (inf.get("state") or "").lower()
    inf_lang = (inf.get("language") or "").lower()

    if target_code == "FR":
        return inf_country == "FR"
    if target_code == "ES":
        return inf_country == "ES"
    if target_code == "MX":
        return inf_country == "MX"
    if target_code == "BR":
        return inf_country == "BR"
    if target_code == "NG":
        return inf_country == "NG"
    if target_code == "GB":
        return inf_country in ["GB", "UK"]
    if target_code == "DE":
        return inf_country == "DE"
    if target_code == "JP":
        return inf_country == "JP"
    if target_code == "KR":
        return inf_country == "KR"
    if target_code == "RU":
        return inf_country == "RU"
    if target_code == "CA":
        return inf_country == "CA"
    if target_code == "AU":
        return inf_country == "AU"
    if target_code == "LK":
        return inf_country == "LK"
    if target_code == "ZA":
        return inf_country in ["ZA", "SA"]
    if target_code == "SOUTH_AMERICA":
        return inf_country in ["BR", "AR", "CO", "CL", "PE", "SOUTH_AMERICA"] or "south america" in inf_region
    if target_code == "AFRICA":
        return inf_country in ["NG", "KE", "TZ", "GH", "ZA", "EG", "AFRICA"] or "africa" in inf_region
    if target_code == "US":
        if "south america" in inf_region or inf_country in ["BR", "AR"]:
            return False
        return inf_country == "US"
    if target_code == "IN_ANDHRA":
        return inf_country == "IN" and (
            bool(re.search(r"\b(andhra|telangana|telugu|hyderabad|vijayawada|vizag)\b", inf_region))
            or "telugu" in inf_lang
        )
    if target_code == "IN_TAMIL":
        return inf_country == "IN" and (
            bool(re.search(r"\b(tamil|chennai|coimbatore)\b", inf_region))
            or "tamil" in inf_lang
        )
    if target_code == "IN":
        return inf_country == "IN"

    # Strict fallback for unmapped custom queries
    for token in raw_query.split():
        token_clean = token.strip().lower()
        if not token_clean:
            continue
        if len(token_clean) <= 3:
            pattern = rf"\b{re.escape(token_clean)}\b"
            if (
                re.search(pattern, inf_country.lower())
                or re.search(pattern, inf_region)
                or re.search(pattern, inf_state)
            ):
                return True
        else:
            if (
                token_clean in inf_country.lower()
                or token_clean in inf_region
                or token_clean in inf_state
                or token_clean in inf_lang
                or token_clean in inf.get("title", "").lower()
                or token_clean in inf.get("top_category", "").lower()
            ):
                return True
    return False
def _fetch_live_youtube_creators(query_or_country: str, limit: int = 10) -> List[Dict[str, Any]]:
    """Live fallback to YouTube API to find trending / top channels for ANY country code."""
    if not YOUTUBE_API_KEY:
        return []

    try:
        yt = build("youtube", "v3", developerKey=YOUTUBE_API_KEY)
        norm_code = COUNTRY_KEYWORD_MAP.get(query_or_country.lower().strip(), query_or_country.upper().strip()[:2])
        if len(norm_code) > 2:
            norm_code = norm_code[:2]

        # 1. Try trending videos in that country
        try:
            resp = yt.videos().list(
                part="snippet",
                chart="mostPopular",
                regionCode=norm_code if len(norm_code) == 2 else "US",
                maxResults=min(50, limit * 3)
            ).execute()
            channel_ids = list({item['snippet']['channelId'] for item in resp.get('items', []) if item.get('snippet', {}).get('channelId')})[:limit]
        except Exception:
            channel_ids = []

        # 2. If trending didn't return, search channels directly
        if not channel_ids:
            search_resp = yt.search().list(
                q=f"top creators in {query_or_country}",
                part="snippet",
                type="channel",
                maxResults=limit
            ).execute()
            channel_ids = [it['snippet']['channelId'] for it in search_resp.get('items', []) if it.get('snippet', {}).get('channelId')]

        if not channel_ids:
            return []

        ch_resp = yt.channels().list(
            part="snippet,statistics",
            id=",".join(channel_ids)
        ).execute()

        live_results = []
        for ch in ch_resp.get("items", []):
            snip = ch.get("snippet", {})
            stats = ch.get("statistics", {})
            subs = int(stats.get("subscriberCount", 0) or 0)
            views = int(stats.get("viewCount", 0) or 0)
            vids = int(stats.get("videoCount", 0) or 0)
            title = snip.get("title", "Creator")
            cid = ch.get("id")
            handle = snip.get("customUrl") or f"@{title.replace(' ', '').lower()}"

            live_results.append({
                "channel_id": cid,
                "handle": handle,
                "title": title,
                "country": snip.get("country") or norm_code,
                "region": f"{snip.get('country') or norm_code} / Featured Creator",
                "state": snip.get("country") or norm_code,
                "language": "Local",
                "top_category": "Entertainment & Media",
                "subscriber_count": subs,
                "total_views": views,
                "total_videos": vids,
                "engagement_rate": 4.5,
                "influencer_type": "Mega (5M+)" if subs >= 5000000 else "Macro (1M - 5M)",
                "thumbnail": snip.get("thumbnails", {}).get("default", {}).get("url", ""),
                "custom_url": f"https://www.youtube.com/{handle}" if handle.startswith("@") else f"https://www.youtube.com/channel/{cid}",
                "est_collab_rate": "Premium Brand Partner",
                "highlights": ["Trending Videos", "Audience Favorite", "High Reach Content"]
            })
        return live_results
    except Exception as e:
        logger.warning("Live YouTube creator fetch error: %s", e)
        return []


def search_catalog(
    country: str | None = None,
    region: str | None = None,
    category: str | None = None,
    min_subscribers: int = 0,
    sort_by: str = "subscribers",
    limit: int = 15
) -> List[Dict[str, Any]]:
    """Search and filter the curated catalog with intelligent multi-country mapping."""
    filtered = list(INFLUENCER_CATALOG)

    raw_query = f"{country or ''} {region or ''}".strip().lower()

    if raw_query and raw_query != "all":
        # Resolve target location code with longest match first & word boundaries
        target_code = None
        for kw, code in sorted(COUNTRY_KEYWORD_MAP.items(), key=lambda x: len(x[0]), reverse=True):
            if re.search(rf"\b{re.escape(kw)}\b", raw_query):
                target_code = code
                break

        if not target_code:
            target_code = raw_query.upper()[:2]

        matched = [inf for inf in filtered if _matches_region(inf, target_code, raw_query)]

        # If catalog has strong matches, use them
        if matched:
            filtered = matched
        else:
            # Fallback to live YouTube search for that country / region
            live_creators = _fetch_live_youtube_creators(raw_query, limit=limit)
            if live_creators:
                filtered = live_creators

    # 2. Match Category
    if category and category.lower() not in ["all", "all categories"]:
        cat_lower = category.lower()
        cat_filtered = [
            inf for inf in filtered
            if cat_lower in inf.get("top_category", "").lower()
            or any(cat_lower in h.lower() for h in inf.get("highlights", []))
        ]
        # Only apply category filter if matches exist, else keep broad to prevent blank screen
        if cat_filtered:
            filtered = cat_filtered

    # 3. Min subscribers
    if min_subscribers > 0:
        sub_filtered = [
            inf for inf in filtered
            if inf.get("subscriber_count", 0) >= min_subscribers
        ]
        if sub_filtered:
            filtered = sub_filtered

        # 4. Sort
    if sort_by == "engagement":
        filtered.sort(key=lambda x: x.get("engagement_rate", 0), reverse=True)
    elif sort_by == "views":
        filtered.sort(key=lambda x: x.get("total_views", 0), reverse=True)
    else:  # default subscribers
        filtered.sort(key=lambda x: x.get("subscriber_count", 0), reverse=True)

    # 5. GUARANTEE MINIMUM 10 INFLUENCERS FOR SELECTED COUNTRY / REGION:
    # If a specific country/region was selected and we have matching verified creators for it:
    if raw_query and raw_query != "all" and 'matched' in locals() and len(matched) >= 10:
        if len(filtered) < 10:
            existing_ids = {c.get("channel_id") for c in filtered}
            for candidate in matched:
                if candidate.get("channel_id") not in existing_ids:
                    filtered.append(candidate)
                    existing_ids.add(candidate.get("channel_id"))
                if len(filtered) >= 10:
                    break

    return filtered[:limit]


def get_channel_insights(channel_id: str) -> Dict[str, Any] | None:
    """Retrieve engagement breakdown and growth rates for a catalog channel."""
    for inf in INFLUENCER_CATALOG:
        if inf.get("channel_id") == channel_id or inf.get("handle", "").lower() == channel_id.lower() or inf.get("title", "").lower() == channel_id.lower():
            return {
                "engagement_scores": inf.get("engagement_scores", {}),
                "growth_rates": inf.get("growth_rates", {}),
                "channel_info": {
                    "title": inf.get("title"),
                    "handle": inf.get("handle"),
                    "region": inf.get("region"),
                    "category": inf.get("top_category"),
                    "est_collab_rate": inf.get("est_collab_rate"),
                    "highlights": inf.get("highlights", [])
                }
            }
    return None
